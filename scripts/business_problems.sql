/*
1. Top Selling Products
Query the top 10 products by total sales value.
Challenge: Include product name, total quantity sold, and total sales value.
*/

--updating table
alter table order_items
add column total_price float;
update order_items
set total_price = quantity * price_per_unit;

select 
	product_name,
	sum(quantity) as total_quantity_sold,
	round(cast(sum(total_price) as decimal),2) as total_sales_value
from products p
inner join order_items oi
on oi.product_id = p.product_id
group by product_name
order by total_sales_value desc
limit 10;


/*
2. Revenue by Category
Calculate total revenue generated by each product category.
Challenge: Include the percentage contribution of each category to total revenue.
*/

select
	*,
	concat(round((total_sales_value/sum(total_sales_value) over())*100,2),'%') Percent_Contribution
from(
	select
		c.category_id,
		category_name,
		round(cast(sum(total_price) as decimal),2) as total_sales_value
	from products p
	inner join order_items oi
	on oi.product_id = p.product_id
	inner join category c
	on p.category_id = c.category_id
	group by category_name,c.category_id
)
order by total_sales_value desc;

/*
3. Average Order Value (AOV)
Compute the average order value for each customer.
Challenge: Include only customers with more than 5 orders.
*/

select
	*,
	round(total_value/orders,2) as avg_order_value
from(
	select
		c.customer_id,
		concat(first_name,' ',last_name) as full_name,
		round(cast(sum(total_price) as decimal),2) as total_value,
		count(oi.order_id) as orders
	from customers c
		inner join orders o
		on o.customer_id = c.customer_id
		inner join order_items oi
		on oi.order_id = o.order_id
	group by c.customer_id,full_name
)
where orders > 5
order by avg_order_value desc;

/*
4. Monthly Sales Trend
Query monthly total sales over the past years.
Challenge: Display the sales trend, grouping by month, return current_month sale with last month sale!
*/

select
	month,
	sales as cm_sales,
	lag(sales,1,0) over(order by month asc) as pm_sales,
	sales - lag(sales,1,0) over(order by month asc) as sales_trend
from (
select
	extract('month' from order_date) as month,
	round(cast(sum(total_price) as decimal),2) as sales
from orders o
inner join order_items oi
on o.order_id = oi.order_id
group by month
order by month
);

-- alternative


with t as(
select max(order_date) as max_date from orders
)

select
	*,
	lag(cm_sales,1,0) over(order by year, month asc) as pm_sales,
	cm_sales - lag(cm_sales,1,0) over(order by year, month asc) as sales_trend,
	concat(round(coalesce((cm_sales/lag(cm_sales) over(order by year,month asc) -1)*100,0),2),'%') as sales_growth
from (
select
	extract('month' from order_date) as month,
	extract('year' from order_date) as year,
	round(cast(sum(total_price) as decimal),2) as cm_sales
from orders o
inner join order_items oi
on o.order_id = oi.order_id
where order_date >= (select max_date from t) - interval '1 year'
group by month, year
)
order by year, month;


