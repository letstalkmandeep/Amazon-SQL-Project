/*
11. Top Performing Sellers
Find the top 5 sellers based on total sales value.
Challenge: Include both successful and failed orders, and display their percentage of successful orders.
*/

with top_sellers as(
select 
	seller_name,
	round(sum(total_price::numeric),2) as total_sales
from sellers s
inner join orders o
on s.seller_id = o.seller_id
inner join order_items as oi
on oi.order_id = o.order_id 
group by seller_name
order by total_sales desc
limit 5
),

seller_report as(
select 
		s.seller_id,
		s.seller_name,
		order_status,
		count(o.order_id)::numeric as total_orders
	from sellers s
	inner join orders o
	on s.seller_id = o.seller_id
	inner join order_items as oi
	on oi.order_id = o.order_id
	inner join top_sellers t
	on t.seller_name = s.seller_name
	where order_status not in ('Inprogress','Returned')
	group by s.seller_name,s.seller_id,order_status
)

select
	*,
	round(completed_orders/total_order*100,2) successful_rate
from(
select 
	seller_id,
	seller_name,
	sum(case when order_status = 'Completed' then total_orders else 0 end) as completed_orders,
	sum(case when order_status = 'Cancelled' then total_orders else 0 end) as cancelled_orders,
	sum(total_orders) as total_order
from seller_report
group by seller_id,seller_name
);

/*
12. Product Profit Margin
Calculate the profit margin for each product (difference between price and cost of goods sold).
Challenge Rank products by their profit margin, showing highest to lowest.
*/

select
	*,
	dense_rank() over(order by profit_margin desc) as Product_Rank
from (
	select
		product_name,
		price,
		cogs,
		price - cogs as Profit,
		round(((price - cogs)/price*100)::numeric,2) as profit_margin
	from products
);

/*
13. Most Returned Products
Query the top 18 products by the number of returns.
Challenge: Display the return rate as a percentage of total units sold for each product.
*/

select
	*,
	round(returns/total_units*100,2) as return_rate
from (
select 
	p.product_id,
	product_name,
	sum(quantity)::numeric as total_units,
	sum(case when order_status = 'Returned' then quantity else 0 end)::numeric as returns
from products p
inner join order_items oi
on oi.product_id = p.product_id
inner join orders o
on o.order_id = oi.order_id
group by p.product_id, product_name)
order by returns desc
limit 18;

/*
14. IDENTITY customers into returning or new
if the customer has done more than 2 return categorize them as returning otherwise new
Challenge: List customers id, name, total orders, total returns
*/


select
	*,
	case when total_returns > 2 then 'Returning' else 'New' end as categorized_customers
from(
select 
	c.customer_id,
	concat(first_name,' ',last_name) as full_name,
	count(order_id) as Total_orders,
	sum(case when order_status = 'Returned' then 1 else 0 end) as total_returns
from customers c
inner join orders o
on c.customer_id = o.customer_id
group by 1,2
)

/*
15. Top 5 Customers by Orders in Each State
Identify the top 5 customers with the highest number of orders for each state.
Challenge: Include the number of orders and total sales for each customer.
*/


select * from (
select
	c.customer_id,
	concat(first_name,' ',last_name) as full_name,
	state,
	count(o.order_id) as total_orders,
	sum(total_price) as total_sales,
