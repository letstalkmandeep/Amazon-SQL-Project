/*
17. Top 20 product with highest decreasing revenue ratio compare to last year (2022) and current year (2023)
Challenge: Return product_id, product_name, category_name, 2022 revenue and 2023 revenue decrease ratio at end Round the result
Note: Decrease ratio cr-ls/ls* 100 (cs current_year ls=last_year)
*/


select
	*,
	round(((revenue_2023/nullif(revenue_2022,0) - 1)*100)::numeric,2) as decrease_ratio
from(
	select
		p.product_id,
		product_name,
		category_name,
		sum(case when extract('year' from order_date) = 2022 then total_price else 0 end)::numeric as Revenue_2022,
		sum(case when extract('year' from order_date) = 2023 then total_price else 0 end)::numeric as Revenue_2023
	from products p
	inner join order_items oi
	on p.product_id = oi.product_id
	inner join orders o
	on o.order_id = oi.order_id
	inner join category c
	on c.category_id = p.category_id
	group by 1,2,3
)
order by decrease_ratio asc
limit 20;




