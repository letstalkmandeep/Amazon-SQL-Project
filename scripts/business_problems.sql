/*
6. Leat-Selling Categories by State
Identify the least-selling category for each state.
Challenge: Include the total sales for that category within each state.
*/

select * from(
select
	state,
	category_name,
	round(sum(total_price::numeric),2) as sales,
	row_number() over(partition by state order by round(sum(total_price::numeric),2) asc) as ranked
from customers c
inner join orders o
on c.customer_id = o.customer_id
inner join order_items oi
on o.order_id = oi.order_id
inner join products p
on oi.product_id = p.product_id
inner join category ct
on p.category_id = ct.category_id
group by state, category_name
) where ranked = 1;


/*
7. Customer Lifetime Value (CLTV)
Calculate the total value of orders placed by each customer over their lifetime.
Challenge: Rank customers based on their CLTV.
*/

select
	*,
	dense_rank() over(order by sales desc) as ranks
from(
select
	c.customer_id,
	concat(first_name,' ',last_name) as full_name,
	sum(total_price::numeric) as sales
from customers c
inner join orders o
on c.customer_id = o.customer_id
inner join order_items oi
on o.order_id = oi.order_id
group by 1,2
);

/*
8. Inventory Stock Alerts
Query products with stock levels below a certain threshold (e.g., less than 10 units).
Challenge: Include last restock date and warehouse information.
*/


select 
	i.inventory_id,
	p.product_id,
	product_name,
	stock,
	last_stock_date,
	warehouse_id
from products p
inner join inventory i
on p.product_id = i.product_id
where stock < 10
order by product_id
;

